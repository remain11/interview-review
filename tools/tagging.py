"""按题目标题粗略推断知识类型标签"""
import re

RULES = [
    ("对比", r"区别|异同|对比|比较|vs|VS|还是|优缺点|相比"),
    ("原理", r"原理|机制|底层|如何实现|怎么实现|实现原理|是什么|为什么|过程|流程"),
    ("场景设计", r"场景|设计|如何保证|怎么保证|如何解决|怎么解决|如何避免|怎么办|如果"),
    ("性能优化", r"优化|性能|加速|延迟|高效|快"),
    ("工具命令", r"命令|工具|排查|查看|gdb|调试"),
    ("手撕", r"^实现|手写|手撕"),
]


def auto_tags(title: str) -> list[str]:
    tags = [name for name, pat in RULES if re.search(pat, title)]
    return tags[:2] or ["概念"]
